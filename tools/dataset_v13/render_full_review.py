    ("트랙 B 20건", "양식에 **`[재현율]`** 칸 추가 (B08은 7/10 간헐적, B13은 비어 있음)", "전체 검토 2차 확인 5"),
    ("63건", "**`[발생 빈도]`** 라벨 신규 → 엄격 기준으로 재라벨링(20건 변경, 모두 값 하나로)", "전체 검토 2차 확인 5, 3차 확인 1"),

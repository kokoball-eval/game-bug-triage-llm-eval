    ("A13·A14·B18", "중복 의심도 기존 이슈의 우선순위 → **Critical**(A13·A14), **Major**(B18)", "전체 검토 3"),
    ("A17", "폐기만 정답", "2차 Q1"),
    ("A20·S03", "**결함 / Major / 등록(재현 대기)** + 개발 QA 재현·어뷰징 테스트", "전체 검토 4·9"),
    ("B04~B10", "등록(재현 대기) → **개발 배정**", "2차 Q2"),
    ("B06", "**Minor**", "전체 검토 5"),

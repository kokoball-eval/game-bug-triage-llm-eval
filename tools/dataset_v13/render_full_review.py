    ("B16·S18", "부정행위 신고: 발생 빈도 **미기재**, 처리 **CS 응대**만 정답", "전체 검토 4·5차"),
    ("S01", "재현 정보 **충분**만 정답 (로그 조회·제재는 운영사 몫)", "전체 검토 4차"),

    ("B17", "모듈 **클라이언트 안정성 / 플랫폼 호환성**", "전체 검토 7"),
    ("B19·S05·S06", "**개선 제안 / Trivial / 개발 배정**, 사람 검토 해제", "전체 검토 10, 2차 확인 3·4"),
    ("S02", "**개선 제안 / Major / 개발 배정**(재현 대기 허용) + 제재 요청은 운영/CS에 별도 전달", "4차 Q3, 전체 검토 8, 2차 확인 3"),
    ("S04", "Critical / 긴급 사인 요청", "4차 Q1"),
    ("S07", "**Major**, 처리 등록(재현 대기)", "전체 검토 11"),

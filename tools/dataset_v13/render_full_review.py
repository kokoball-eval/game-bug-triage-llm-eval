def main(out_path):
    d = json.loads(DATA.read_text(encoding="utf-8"))
    items = d["items"]

    def first(f):
        return Counter(i["labels"][f][0] for i in items if i["labels"][f])

    def dist(f):
        c = first(f)
        return " · ".join(f"{k} {c[k]}" for k in m.ENUMS[f] if c.get(k))

    H = [f"""# Aether Raid 버그 트리아지 평가셋 v1.3 — 전체 검토본 5판 (63건)

> 2026-10-01
> 전체 검토 1차 의견 12건, 2차 확인 5건, 3차 확인 2건, 4차 의견 3건, 5차 확인 1건을 반영한 최종본입니다. 파일: `data/eval_v13/aether_raid_v13.json`
> 이번에 바뀐 부분은 §4 마지막 세 줄(B16·S18·S01·S14)과 §5 "해당 없음" 정의입니다.

## 1. 한눈에 보기

| 세트 | 건수 | 구성 | 재는 것 |
| :--- | ---: | :--- | :--- |
| 대표 세트 | 40 | 트랙 A(커뮤니티 원문) 20 + 트랙 B(QA 작성 이슈) 20, **실무 비율대로** | 자동 처리율, 자동 처리분 정확도 |
| 집중 세트 | 23 | 운영 불만형 5, 경계 규칙 8, 감정 속 진짜 결함 6, 확인 필요 2, 거짓 경보 2 | 위험 건 누락(X-1~X-3), 과잉 상신 |

- **라벨 읽는 법:** 각 칸은 허용 답 목록이고 첫 번째 값이 가장 바람직한 답입니다.
- **`긴급 사인 요청`:** Critical 후보를 리드 QA(부재 시 지정 대리자)에게 즉시 알려 사인을 받은 뒤 개발에 전달합니다. 자동화는 Critical을 개발에 직접 보내지 않으므로 이 건은 자동 처리율에 넣지 않습니다.

## 2. 개발용/평가용 분할

위험 건 측정 문항(사람 검토, Critical)을 먼저 번갈아 나누고, 나머지를 같은 성격끼리 번갈아 나눴습니다. 난수를 쓰지 않아 다시 실행해도 같은 결과가 나옵니다.

| 세트 | 분할 | 건수 | Critical 사인 요청(X-1) | 결함 폐기 금지(X-2) | 사람 검토(X-3) | 트랙 B |
| :--- | :--- | ---: | ---: | ---: | ---: | ---: |
"""]
    for r in d["split_summary"]:
        H.append(f"| {'대표' if r['set'] == 'representative' else '집중'} | `{r['split']}` | {r['n']} | "
                 f"{r['Critical(X-1)']} | {r['결함 폐기 금지(X-2)']} | {r['사람 검토(X-3)']} | {r['트랙 B']} |\n")
    H.append(f"""
## 3. 커버리지 (첫 번째 정답 기준)

| 항목 | 분포 |
| :--- | :--- |
| 분류 | {dist('분류')} |
| 우선순위 | {dist('우선순위')} |
| 처리 | {dist('처리')} |
| 발생 빈도 | {dist('발생 빈도')} |
| 모듈 | {dist('모듈')} |
| 사람 검토 필요 | {sum(i['labels']['human_review'] for i in items)}건 |

## 4. 배치 검토 뒤 바뀐 라벨

| 문항 | 바뀐 내용 | 근거 (검토 기록) |
| :--- | :--- | :--- |
""")
    for a, b, c in CHANGES:
        H.append(f"| {a} | {b} | {c} |\n")

    H.append("""
## 5. `[발생 빈도]` 라벨 (전체 검토 3차 기준으로 재라벨링)

리포트에 **적힌** 빈도만 옮기고 추론하지 않습니다(기준서 F-1). 그래서 문항마다 값이 하나로 정해집니다.

| 값 | 원문 표현 |
| :--- | :--- |
| 항상 | 매번, 무조건, 100%, "세 번 다", 트랙 B 재현율 100% |
| 간헐적 | 계속, 여러 번, "오늘만 세 번째", 트랙 B 재현율 100% 미만 |
| 1회 | 한 번 일어난 사건 (결제 1건, 점검 후 데이터 소실) |
| 미기재 | 조건문("~하면 ~됨"), 플랫폼 범위("아이폰이든 PC든 똑같음"), 방법 설명, 빈도 표현 없음 |
| 해당 없음 | 결함 현상을 다루지 않는 글(무관, 개선 제안, 순수 문의·건의). 부정행위 신고처럼 현상이 있으면 미기재. 결함으로도 볼 수 있는 문항(A09·S17·S20 등)은 결함으로 판정했을 때의 **미기재**도 허용 — 두 값이 허용되는 건 이 경우뿐 |

**빈도와 우선순위 (기준서 F-2):** 항상·간헐적이면 Critical 유지. 1회면 Major~Minor까지 열어 두되 크래시처럼 심각하면 Major. 결제·재화 피해, 데이터 소실·롤백, 다수 유저 서버 장애는 1회여도 Critical.

| 값 | 문항 |
| :--- | :--- |
""")
    for v in m.ENUMS["발생 빈도"]:
        ids = [i["id"] for i in items if i["labels"]["발생 빈도"][0] == v]
        H.append(f"| {v} ({len(ids)}) | {', '.join(ids)} |\n")
    H.append("""
## 6. 병합할 때 자동으로 확인한 것

`tools/merge_dataset.py`가 아래를 검사하고, 하나라도 어긋나면 파일을 쓰지 않습니다. 63건 모두 통과했습니다.

- ID 중복 없음, 63건 모두 검토 승인 상태, 발생 빈도 라벨이 63건 모두에 있음
- 라벨 값이 기준서의 허용 값 안에 있음 (처리 값은 `긴급 사인 요청` 포함 6개, 발생 빈도 5개)
- 규칙 간 일관성: 트랙 A의 `개발 배정`은 개선 제안만(H-2d) / 결함·중복이면 발생 빈도가 해당 없음이 아님 / X-1 문항은 긴급 사인 요청이 정답에 있음 / X-3 문항은 사람 검토 표시 / 발생 빈도 1회인데 Critical이면 F-2 예외(결제·재화, 계정·데이터, 서버 장애)에 해당

---

""")
    sections = [
        ("7. 대표 세트 — 트랙 A 커뮤니티 원문 (20건)", lambda i: i["set"] == "representative" and i["track"] == "A"),
        ("8. 대표 세트 — 트랙 B QA 작성 이슈 (20건)", lambda i: i["set"] == "representative" and i["track"] == "B"),
        ("9. 집중 세트 (23건)", lambda i: i["set"] == "focused"),
    ]
    tmp = Path(out_path).with_suffix(".tmp.json")
    body = []
    for title, f in sections:
        tmp.write_text(json.dumps({"items": [i for i in items if f(i)]}, ensure_ascii=False), encoding="utf-8")
        body.append(f"## {title}\n\n{render(tmp)}\n")
    tmp.unlink()
    Path(out_path).write_text("".join(H) + "".join(body), encoding="utf-8")
    print(f"저장: {out_path} (문항 {len(items)}건)")


if __name__ == "__main__":
    main(sys.argv[1])

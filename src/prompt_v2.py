TRACK_LABEL = {"A": "(A) 커뮤니티 제보 원문", "B": "(B) QA 작성 BTS 이슈"}


def build_input(item: dict) -> str:
    """평가셋 문항 1건을 모델 입력 문자열로 만든다 (설계 의도 3·4)."""
    inp = item["input"]
    lines = [f"[입력 종류] {TRACK_LABEL[item['track']]}"]
    if item["track"] == "A":
        lines += [f"[게시판] {inp['board']}", f"[게시 일시] {inp['posted_at']}"]
    else:
        lines += [f"[작성자] {inp['reporter']}"]
    lines += [f"[제목] {inp['title']}", "[본문]", inp["body"]]
    ctx = inp.get("context", {})
    lines += ["", "[참고: 업데이트 공지]", ctx.get("update_note", "")]
    lines += ["[참고: 기존 등록 이슈]"] + [f"- {k}" for k in ctx.get("known_issues", [])]
    return "\n".join(lines)


def build_prompt(item: dict) -> str:
    return f"{SYSTEM_PROMPT_V2}\n[리포트]\n{build_input(item)}"


def build_retry_prompt(item: dict, previous: str, errors: list[tuple[str, str | None]],
                       recheck: tuple[str, ...] = (), lang_errors: list[tuple[str, str]] = ()) -> str:
    """형식 위반 필드만 1회 다시 요청하는 프롬프트 (설계 의도 5·6).

    errors      허용 값 밖인 선택지 필드 (R6)
    recheck     값은 허용 값이지만 틀린 필드에 기대어 정해졌을 수 있어 함께 다시 정할 필드(예: 분류가 틀렸으면 처리)
    lang_errors 출력 언어 밖 문자가 섞인 자유 서술 필드와 그 문자 (R7)
    """
    lines = ["", "[이전 응답]", previous.strip(), "", "[형식 오류]"]
    for field, value in errors:
        allowed = ENUMS_V2.get(field) or (MODULES + [NO_MODULE])
        shown = "값 없음" if value is None else f"'{value}'"
        lines.append(f"- [{field}]의 {shown}은(는) 허용 값이 아닙니다. 허용 값: {', '.join(allowed)}")
    for field in recheck:
        lines.append(f"- [{field}]는 위 필드를 고친 뒤 그 판단에 맞게 다시 정하세요. 허용 값: {', '.join(ENUMS_V2[field])}")
    lang = LANG_NAMES[OUTPUT_LANG]
    for field, chars in lang_errors:
        lines.append(f"- [{field}]에 {lang}가 아닌 문자 '{chars}'가 섞여 있습니다. 같은 내용을 {lang}로만, 한 줄로 다시 쓰세요. "
                     "입력에 없는 내용을 더하지 마세요.")
    fields = [f for f, _ in errors] + list(recheck) + [f for f, _ in lang_errors]
    lines.append(f"위 필드({', '.join(fields)})만 다시 정해 JSON으로 출력하세요. 키는 필드명입니다. "
                 "선택지가 있는 필드의 값은 허용 값 중 하나입니다. 다른 필드는 출력하지 마세요.")
    return build_prompt(item) + "\n".join(lines)


